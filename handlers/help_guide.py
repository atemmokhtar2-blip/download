def _home_markup(uid: int) -> InlineKeyboardMarkup:
    rows = [[InlineKeyboardButton(label, callback_data=f"guide:section:{key}:{uid}")]
            for label, key in LABELS]
    rows.append([InlineKeyboardButton("🎁 افتح صفحة امتلاك نسختي", callback_data=f"guide:copy:{uid}")])
    rows.append([InlineKeyboardButton("✖️ إغلاق الدليل", callback_data=f"guide:close:{uid}")])
    return InlineKeyboardMarkup(rows)


def help_guide_markup(user_id: int) -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup([[
        InlineKeyboardButton("📖 شرح البوت بالكامل", callback_data=f"guide:home:{int(user_id)}")
    ]])


async def help_guide_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    if query is None:
        return
    parts = (query.data or "").split(":")
    if len(parts) < 3 or not parts[-1].isdigit():
        await query.answer("انتهت صلاحية هذا الزر.", show_alert=True)
        return
    uid = int(parts[-1])
    if query.from_user.id != uid:
        await query.answer("الدليل ده اتفتح لحساب مستخدم آخر.", show_alert=True)
        return

    action = parts[1]
    if action == "copy":
        await query.answer()
        from handlers.referral import referral_page
        await referral_page(update, context, edit=True)
        return

    await query.answer()
    if action == "close":
        await query.edit_message_text("تم إغلاق دليل الشرح. تقدر تفتحه مرة أخرى من الإعدادات.")
    elif action == "section" and len(parts) == 4 and parts[2] in SECTIONS:
        key = parts[2]
        rows = [
            [InlineKeyboardButton("📚 كل أقسام الدليل", callback_data=f"guide:home:{uid}")],
        ]
        if key == "copy":
            rows.append([InlineKeyboardButton("🎁 افتح صفحة امتلاك نسختي", callback_data=f"guide:copy:{uid}")])
        rows.append([InlineKeyboardButton("✖️ إغلاق الدليل", callback_data=f"guide:close:{uid}")])
        await query.edit_message_text(
            SECTIONS[key], parse_mode="HTML",
            reply_markup=InlineKeyboardMarkup(rows),
            disable_web_page_preview=True,
        )
    else:
        await query.edit_message_text(
            HOME, parse_mode="HTML", reply_markup=_home_markup(uid),
            disable_web_page_preview=True,
        )
